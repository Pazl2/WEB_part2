// Единое место для лимитов и допустимых значений. Клиент дублирует часть из них
// (maxLength в формах), но проверяет и принимает решение всегда сервер.

const CATEGORIES = ['Общее', 'Границы', 'Стоянки', 'Дороги'];

module.exports = {
  CATEGORIES,
  DEFAULT_CATEGORY: 'Общее',

  TITLE_MAX: 150,
  CONTENT_MAX: 10000,
  TAG_MAX_LENGTH: 30,
  TAGS_MAX_COUNT: 10,

  COMMENT_MAX: 500,
  // Комментарии лежат внутри документа поста, а документ в MongoDB не больше 16 МБ,
  // поэтому их число ограничено
  COMMENTS_MAX_PER_POST: 500,

  SEARCH_MAX: 100,
  PAGE_SIZE_DEFAULT: 10,
  PAGE_SIZE_MAX: 50,
  PAGE_MAX: 100000,

  USERNAME_MIN: 3,
  USERNAME_MAX: 24,

  // --- Чат и уведомления в реальном времени (WebSocket, Socket.IO) ---
  // Комнаты чата совпадают с категориями постов
  CHAT_ROOMS: CATEGORIES,
  CHAT_MESSAGE_MAX: 500,
  // Сколько последних сообщений сервер отдаёт при входе в комнату / открытии диалога
  CHAT_HISTORY_LIMIT: 50,
  // Не более 10 сообщений за 10 секунд на пользователя (на все его вкладки вместе)
  CHAT_RATE: { windowMs: 10 * 1000, max: 10 },
  // События «печатает» — отдельный, более мягкий лимит (клиент шлёт их не чаще раза в 2 с)
  TYPING_RATE: { windowMs: 10 * 1000, max: 20 },
  // Максимальный размер одного пакета Socket.IO. Больший пакет сервер не принимает
  // и закрывает соединение (500 символов кириллицы — это около 1 КБ).
  SOCKET_MAX_PAYLOAD_BYTES: 8 * 1024,
  // Не более стольких одновременных соединений (вкладок) от одного пользователя
  SOCKET_MAX_PER_USER: 5,
};
